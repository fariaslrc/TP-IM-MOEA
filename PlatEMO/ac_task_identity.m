function [hash,identity] = ac_task_identity(t,sourceDigest)
%AC_TASK_IDENTITY Relocatable scientific identity; output path is excluded.
    identity = struct('schemaVersion',t.schemaVersion,'block',t.block, ...
        'algName',t.algName,'profile',t.config,'probName',t.probName,'M',t.M, ...
        'D',t.D,'N',t.N,'maxFE',t.maxFE,'run',t.run,'seedName',t.seedName, ...
        'seed',t.seed,'protocol',t.protocol,'saveNum',t.saveNum, ...
        'param',{t.param},'sourceDigest',sourceDigest);
    hash = ac_sha256(jsonencode(identity));
end
